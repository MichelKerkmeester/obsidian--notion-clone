#!/usr/bin/env node
// ───────────────────────────────────────────────────────────────────
// MODULE:    rename-prefixes
// COMPONENT: the 068 rename-to-obnotion mechanical prefix sweep
// ───────────────────────────────────────────────────────────────────
//
// Five plain substring/regex rules, applied in order to every text file under
// the scanned roots. The rules target disjoint text (verified against the
// packet's own census before this script was written — see the packet's
// handover), so the order among them does not change the result:
//
//   1. "Note Database"  -> "Obnotion"   (title case, the display string)
//   2. "NoteDatabase"    -> "Obnotion"   (PascalCase identifiers)
//   3. "noteDatabase"    -> "obnotion"   (camelCase identifiers)
//   4. "note-database"   -> "obnotion"   (kebab-case identifiers, covers
//                                          every compound like
//                                          note-database-container)
//   5. /\bdb-/g          -> "obnotion-"  (the bare class/custom-property
//                                          prefix; a word boundary sits right
//                                          after the leading "--" on a custom
//                                          property too, so this one rule
//                                          also rewrites --db-* correctly)
//
// `db_view` (underscore, not hyphen) never matches rule 5 and needs no
// special-casing. Every alias this rename keeps permanently — the two
// code-block languages, the two view types, the export marker — is added
// to the source AFTER this script runs, by hand, never generated by it:
// a blind substitution has no way to tell "this occurrence is the
// intentional backward-compat literal" from "this one is the general
// identifier", so the two categories are kept apart by WHEN the literal
// is written, not by a runtime exception list here.
//
// Scope is narrower than "everywhere `note-database` appears" for two
// reasons, both a reviewer should be able to verify independently:
//
//   - `README.md` and `update-fork.sh` are excluded outright. Both carry a
//     credit to upstream's own repository and product name
//     (`pangy9/obsidian-note-database`, "[Note Database](...)"), which must
//     never be renamed — it is not our product. Every OTHER occurrence in
//     both files was already rewritten by the parallel README leg before
//     this script runs (`git grep -c -E 'note-database|\bdb-' -- README.md`
//     is 2, both upstream credit; `update-fork.sh` is 1, same reason), so
//     excluding the whole file loses nothing and cannot mis-rename upstream.
//   - `tools/lane/css-lane.json` IS included (an earlier draft of this script
//     excluded it, on the theory that its 380+-entry `history` journal
//     describes what selectors existed AT THE TIME of a past edit and
//     shouldn't be made to say a class name existed in the past that did
//     not). That theory does not survive contact with this packet's own
//     frozen acceptance criteria: the count this rename must reach is a
//     literal grep with no carve-out for this one file, and every past
//     decision this journal records — which surface, which rule, which
//     capture — is unaffected by which spelling of the class name the prose
//     uses to name it. The full historical wording is never actually lost
//     either: it still lives in every commit before this one.
//     `holder`/`acquiredAt`/`baselineHash` and any newly appended history
//     entry are still edited by hand, separately, both to acquire the lane
//     and to hand it back with the new hash.
//   - `screenshots/manifest.json` is excluded. It is fully regenerated by
//     `npm run screenshots` from the (already-swept) scenario source, so
//     sweeping it here would just be overwritten by the recapture anyway.
//
// Usage:
//   node tools/naming/rename-prefixes.mjs --check   # report only, exit 1 if any match remains
//   node tools/naming/rename-prefixes.mjs            # rewrite in place
//
// Re-running in apply mode is a no-op: once every occurrence is converted,
// none of the five patterns has anything left to match.

// ───────────────────────────────────────────────────────────────────
// 1. IMPORTS
// ───────────────────────────────────────────────────────────────────

import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// ───────────────────────────────────────────────────────────────────
// 2. CONFIGURATION
// ───────────────────────────────────────────────────────────────────

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

// Roots the sweep walks. Each is relative to REPO_ROOT and may be a file or
// a directory walked recursively.
const SCAN_ROOTS = [
  "styles.css",
  "src",
  "tools",
  ".storybook",
  "manifest.json",
  "package.json",
  "package-lock.json",
];

// Exact repo-relative paths never touched, regardless of extension — see the
// rationale in the header comment above.
const EXCLUDED_FILES = new Set([
  // Its own source: every rule below is written as a literal string the rule
  // itself targets ("Note Database", "note-database", ...), documented in
  // English prose that also uses those words. Sweeping this file would
  // rewrite its own rule definitions into no-ops.
  "tools/naming/rename-prefixes.mjs",
]);

// Directories never descended into.
const EXCLUDED_DIR_NAMES = new Set(["node_modules", ".git"]);

// Only files with one of these extensions are read as text. Everything else
// under the scanned roots (binary fixtures, fonts, etc.) is skipped.
const TEXT_EXTENSIONS = new Set([
  ".ts", ".tsx", ".js", ".mjs", ".cjs",
  ".css", ".json", ".md", ".sh", ".html", ".yml", ".yaml",
]);

const RULES = [
  { label: "Note Database -> Obnotion", apply: (s) => s.replaceAll("Note Database", "Obnotion") },
  { label: "NoteDatabase -> Obnotion", apply: (s) => s.replaceAll("NoteDatabase", "Obnotion") },
  { label: "noteDatabase -> obnotion", apply: (s) => s.replaceAll("noteDatabase", "obnotion") },
  { label: "note-database -> obnotion", apply: (s) => s.replaceAll("note-database", "obnotion") },
  { label: "\\bdb- -> obnotion-", apply: (s) => s.replace(/\bdb-/g, "obnotion-") },
];

// ───────────────────────────────────────────────────────────────────
// 3. FILE DISCOVERY
// ───────────────────────────────────────────────────────────────────

function relPath(absPath) {
  return path.relative(REPO_ROOT, absPath).split(path.sep).join("/");
}

function collectFiles(root) {
  const absRoot = path.join(REPO_ROOT, root);
  let stat;
  try {
    stat = statSync(absRoot);
  } catch {
    return [];
  }
  if (stat.isFile()) return [absRoot];

  const out = [];
  const stack = [absRoot];
  while (stack.length > 0) {
    const dir = stack.pop();
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (EXCLUDED_DIR_NAMES.has(entry.name)) continue;
        stack.push(path.join(dir, entry.name));
        continue;
      }
      if (!entry.isFile()) continue;
      const abs = path.join(dir, entry.name);
      if (!TEXT_EXTENSIONS.has(path.extname(entry.name))) continue;
      if (EXCLUDED_FILES.has(relPath(abs))) continue;
      out.push(abs);
    }
  }
  return out;
}

function allFiles() {
  const seen = new Set();
  const files = [];
  for (const root of SCAN_ROOTS) {
    for (const abs of collectFiles(root)) {
      const rel = relPath(abs);
      if (seen.has(rel)) continue;
      seen.add(rel);
      files.push(abs);
    }
  }
  return files.sort();
}

// ───────────────────────────────────────────────────────────────────
// 4. REWRITE
// ───────────────────────────────────────────────────────────────────

/** Applies every rule in order and returns the final text, whether or not it changed. */
export function rewrite(text) {
  let out = text;
  for (const rule of RULES) out = rule.apply(out);
  return out;
}

/** True when at least one rule's source pattern still occurs in the text. */
export function hasResidue(text) {
  return (
    text.includes("Note Database") ||
    text.includes("NoteDatabase") ||
    text.includes("noteDatabase") ||
    text.includes("note-database") ||
    /\bdb-/.test(text)
  );
}

// ───────────────────────────────────────────────────────────────────
// 5. MAIN
// ───────────────────────────────────────────────────────────────────

function main() {
  const check = process.argv.includes("--check");
  const files = allFiles();

  let filesWithResidue = 0;
  let filesChanged = 0;
  const residueLines = [];

  for (const abs of files) {
    const rel = relPath(abs);
    const before = readFileSync(abs, "utf8");
    if (!hasResidue(before)) continue;

    if (check) {
      const count = (before.match(/Note Database|NoteDatabase|noteDatabase|note-database|\bdb-/g) || []).length;
      filesWithResidue += 1;
      residueLines.push(`  ${rel}: ${count} occurrence(s)`);
      continue;
    }

    const after = rewrite(before);
    if (after !== before) {
      writeFileSync(abs, after, "utf8");
      filesChanged += 1;
    }
  }

  if (check) {
    if (filesWithResidue === 0) {
      console.log("rename-prefixes --check: 0 files with a remaining note-database/db- occurrence");
      return 0;
    }
    console.log(`rename-prefixes --check: ${filesWithResidue} file(s) still hold a note-database/db- occurrence:`);
    for (const line of residueLines) console.log(line);
    return 1;
  }

  console.log(`rename-prefixes: rewrote ${filesChanged} file(s)`);
  return 0;
}

const invoked = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invoked) process.exit(main());
