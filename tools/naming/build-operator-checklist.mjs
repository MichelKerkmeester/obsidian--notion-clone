// ───────────────────────────────────────────────────────────────────
// MODULE:    build-operator-checklist
// COMPONENT: derives the one list only a device can close
// ───────────────────────────────────────────────────────────────────
//
// Every phase in this program ends the same way: a row nothing here can close, because it asks what
// a person sees on their own phone with their own vault. Those rows are scattered one per packet
// across thirty-odd folders, which is the right place to record them and the wrong place to act on
// them — nobody opens thirty files to find out what to check.
//
// So this collects them. It reads the unticked rows out of every phase's own checklist and writes
// them as one list, with the phase's derived figure beside each. It invents nothing: a row appears
// here because it is unticked there, and the figure is a count of checkboxes rather than a judgement.
//
// Regenerating it after any checklist edit is the point — a hand-maintained copy of thirty files is
// a thirty-first place to be wrong.
//
// `--check` regenerates in memory and compares instead of writing, exiting non-zero on drift. A
// generated file nobody regenerates is the doc-truth failure this program exists to catch, and
// shipping one without a guard would be adding an instance of it.
//
// Usage:
//   node tools/naming/build-operator-checklist.mjs
//   node tools/naming/build-operator-checklist.mjs --check

// ───────────────────────────────────────────────────────────────────
// 1. IMPORTS
// ───────────────────────────────────────────────────────────────────

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

// ───────────────────────────────────────────────────────────────────
// 2. CONSTANTS
// ───────────────────────────────────────────────────────────────────

const REPO = fileURLToPath(new URL("../..", import.meta.url));
const PROGRAM = join(REPO, "specs/005-component-surface-system");
const OUT = join(PROGRAM, "operator-checklist.md");

// ───────────────────────────────────────────────────────────────────
// 3. COLLECT
// ───────────────────────────────────────────────────────────────────

/** The first line of each unticked row, with its continuation prose dropped. */
function openRows(text) {
  const rows = [];
  const lines = text.split("\n");
  for (let i = 0; i < lines.length; i += 1) {
    if (!lines[i].startsWith("- [ ]")) continue;
    let row = lines[i].slice(5).trim();
    // A row's first sentence is the ask; everything after is the evidence trail.
    for (let j = i + 1; j < lines.length && !lines[j].startsWith("- ["); j += 1) {
      const cont = lines[j].trim();
      if (!cont || cont.startsWith("**") || cont.startsWith("<!--")) break;
      row += ` ${cont}`;
      if (/[.!?]$/.test(cont)) break;
    }
    rows.push(row.replace(/\s+/g, " ").replace(/\*\*/g, "").trim());
  }
  return rows;
}

const phases = [];
for (const name of readdirSync(PROGRAM).sort()) {
  let goal;
  try {
    goal = readFileSync(join(PROGRAM, name, "goal.md"), "utf8");
  } catch {
    continue;
  }
  const done = (goal.match(/\n- \[x\]/g) || []).length;
  const open = openRows(goal);
  if (done + open.length === 0) continue;
  phases.push({ name, done, total: done + open.length, open });
}

// ───────────────────────────────────────────────────────────────────
// 4. WRITE
// ───────────────────────────────────────────────────────────────────

const waiting = phases.filter((p) => p.open.length);
const complete = phases.filter((p) => !p.open.length);
const rowCount = waiting.reduce((n, p) => n + p.open.length, 0);

// The output is a spec document like any other, so it carries the frontmatter the corpus
// convention requires. Without it the file has no retrievable trigger phrases, and the parent
// packet fails GREP_CONVENTION on a file no hand-edit can fix — the producer has to emit it.
const frontmatter = [
  "---",
  'title: "Operator Checklist"',
  'description: "Every row across the program that only a device can close, gathered from each phase\'s own goal.md."',
  "trigger_phrases:",
  '  - "operator checklist"',
  '  - "device confirmation list"',
  '  - "what the operator still has to check"',
  '  - "rows only a device closes"',
  'importance_tier: "important"',
  'contextType: "reference"',
  "---",
];

const body = [
  ...frontmatter,
  "# Operator checklist",
  "",
  "<!-- GENERATED by tools/naming/build-operator-checklist.mjs — edit the phase checklists, not this file. -->",
  "",
  "Every row below is unticked in its own phase's `goal.md` and nothing in this repository can close",
  "it. They are gathered here because one list is actionable and thirty files are not.",
  "",
  `Derived ${new Date().toISOString().slice(0, 10)}: **${phases.length} phases**, `
    + `**${complete.length} with nothing left**, **${rowCount} rows** waiting on a device.`,
  "",
  "The figure beside each phase is a count of its own checkboxes. It is derived, never judged.",
  "",
];

for (const p of waiting) {
  body.push(`## ${p.name} — ${p.done}/${p.total}`, "");
  for (const row of p.open) body.push(`- [ ] ${row}`);
  body.push("");
}

if (complete.length) {
  body.push("## Nothing left to check", "");
  for (const p of complete) body.push(`- ${p.name} — ${p.done}/${p.total}`);
  body.push("");
}

const rendered = `${body.join("\n")}\n`;

// The derived date changes every day and says nothing about whether the rows moved, so drift is
// compared on everything else. A checklist that differed only by its own timestamp would fail this
// every morning and teach the reader to ignore it.
const withoutDate = (text) => text.replace(/^Derived \d{4}-\d{2}-\d{2}:/m, "Derived:");

if (process.argv.includes("--check")) {
  if (!existsSync(OUT)) {
    console.error("operator-checklist: FAIL — the checklist has never been generated.");
    process.exit(1);
  }
  const onDisk = readFileSync(OUT, "utf8");
  if (withoutDate(onDisk) !== withoutDate(rendered)) {
    console.error(`operator-checklist: FAIL — the checklist is stale against the phase checklists.`);
    console.error("  A row was ticked, added or reworded and this was not regenerated.");
    console.error("  Run: node tools/naming/build-operator-checklist.mjs");
    process.exit(1);
  }
  console.log(`operator-checklist: PASS — ${rowCount} row(s) across ${waiting.length} phase(s), current`);
  process.exit(0);
}

writeFileSync(OUT, rendered, "utf8");
console.log(`operator-checklist: ${rowCount} row(s) across ${waiting.length} phase(s) -> ${OUT.replace(REPO, "")}`);
